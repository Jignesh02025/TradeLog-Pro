export const DEFAULT_CUSTOM_THEME = {
  base: 'dark-slate', // 'dark-slate' | 'pitch-black' | 'deep-midnight' | 'espresso' | 'light' | 'custom'
  customBg: '#0a0f1e',
  primaryColor: '#3b82f6',
  secondaryColor: '#8b5cf6',
  cardStyle: 'glass', // 'glass' | 'solid' | 'tinted'
  glowIntensity: 'medium', // 'subtle' | 'medium' | 'vivid'
}

// Color Utility Helpers
export function hexToRgb(hex) {
  if (!hex) return { r: 59, g: 130, b: 246 }
  let clean = hex.replace('#', '')
  if (clean.length === 3) {
    clean = clean.split('').map(c => c + c).join('')
  }
  const num = parseInt(clean, 16)
  if (isNaN(num)) return { r: 59, g: 130, b: 246 }
  return {
    r: (num >> 16) & 255,
    g: (num >> 8) & 255,
    b: num & 255,
  }
}

export function rgbaString(hex, alpha = 1) {
  const { r, g, b } = hexToRgb(hex)
  return `rgba(${r}, ${g}, ${b}, ${alpha})`
}

export function getLuminance(hex) {
  const { r, g, b } = hexToRgb(hex)
  return 0.2126 * (r / 255) + 0.7152 * (g / 255) + 0.0722 * (b / 255)
}

export function adjustBrightness(hex, percent) {
  const { r, g, b } = hexToRgb(hex)
  const amt = Math.round(2.55 * percent)
  const newR = Math.max(0, Math.min(255, r + amt))
  const newG = Math.max(0, Math.min(255, g + amt))
  const newB = Math.max(0, Math.min(255, b + amt))
  return `#${((1 << 24) + (newR << 16) + (newG << 8) + newB).toString(16).slice(1)}`
}

// Generate complete CSS variables from Custom Theme Studio configuration
export function generateCustomThemeVars(custom) {
  const cfg = { ...DEFAULT_CUSTOM_THEME, ...(custom || {}) }
  
  let bgPrimary = '#0a0f1e'
  let bgSecondary = '#0f172a'
  let bgCard = '#111827'
  let bgCardHover = '#1a2235'
  let isLight = false

  switch (cfg.base) {
    case 'pitch-black':
      bgPrimary = '#000000'
      bgSecondary = '#09090b'
      bgCard = '#121214'
      bgCardHover = '#1c1c20'
      break
    case 'deep-midnight':
      bgPrimary = '#080811'
      bgSecondary = '#0f0f1c'
      bgCard = '#141424'
      bgCardHover = '#1d1d33'
      break
    case 'espresso':
      bgPrimary = '#100c0a'
      bgSecondary = '#17120e'
      bgCard = '#1f1914'
      bgCardHover = '#2c231d'
      break
    case 'light':
      bgPrimary = '#f1f5f9'
      bgSecondary = '#ffffff'
      bgCard = '#ffffff'
      bgCardHover = '#f8fafc'
      isLight = true
      break
    case 'custom':
      bgPrimary = cfg.customBg || '#0a0f1e'
      isLight = getLuminance(bgPrimary) > 0.5
      bgSecondary = isLight ? adjustBrightness(bgPrimary, -6) : adjustBrightness(bgPrimary, 8)
      bgCard = isLight ? '#ffffff' : adjustBrightness(bgPrimary, 14)
      bgCardHover = isLight ? '#f1f5f9' : adjustBrightness(bgPrimary, 22)
      break
    case 'dark-slate':
    default:
      bgPrimary = '#0a0f1e'
      bgSecondary = '#0f172a'
      bgCard = '#111827'
      bgCardHover = '#1a2235'
      break
  }

  const primary = cfg.primaryColor || '#3b82f6'
  const secondary = cfg.secondaryColor || '#8b5cf6'

  // Glow alphas
  let glowAlpha = 0.35
  let glowStrongAlpha = 0.55
  if (cfg.glowIntensity === 'subtle') {
    glowAlpha = 0.18
    glowStrongAlpha = 0.3
  } else if (cfg.glowIntensity === 'vivid') {
    glowAlpha = 0.55
    glowStrongAlpha = 0.8
  }

  // Card background styling
  let glassBg = rgbaString(bgCard, 0.88)
  if (cfg.cardStyle === 'solid') {
    glassBg = bgCard
  } else if (cfg.cardStyle === 'tinted') {
    glassBg = `linear-gradient(135deg, ${rgbaString(bgCard, 0.92)}, ${rgbaString(primary, 0.08)})`
  }

  const textPrimary = isLight ? '#0f172a' : '#f8fafc'
  const textSecondary = isLight ? '#334155' : '#cbd5e1'
  const textMuted = isLight ? '#64748b' : '#94a3b8'
  const borderColor = isLight ? 'rgba(15, 23, 42, 0.1)' : rgbaString(primary, 0.18)
  const cardBorder = isLight ? 'rgba(15, 23, 42, 0.08)' : rgbaString(primary, 0.14)
  const cardHoverBorder = rgbaString(primary, 0.45)
  const bgInput = isLight ? '#ffffff' : rgbaString(bgCard, 0.85)

  return {
    '--bg-primary': bgPrimary,
    '--bg-secondary': bgSecondary,
    '--bg-card': bgCard,
    '--bg-card-hover': bgCardHover,
    '--border-color': borderColor,
    '--text-primary': textPrimary,
    '--text-secondary': textSecondary,
    '--text-muted': textMuted,
    '--accent-blue': primary,
    '--accent-blue-dark': adjustBrightness(primary, -20),
    '--accent-green': '#10b981',
    '--accent-red': '#ef4444',
    '--accent-yellow': '#f59e0b',
    '--accent-purple': secondary,
    '--accent-orange': '#f97316',
    '--bg-input': bgInput,
    '--glass-bg': glassBg,
    '--stat-card-bg': `linear-gradient(135deg, ${bgCard} 0%, ${bgSecondary} 100%)`,
    '--sidebar-bg': `linear-gradient(180deg, ${bgSecondary} 0%, ${bgPrimary} 100%)`,
    '--topbar-bg': `linear-gradient(180deg, ${bgSecondary} 0%, ${bgPrimary} 100%)`,
    '--card-border': cardBorder,
    '--card-hover-border': cardHoverBorder,
    '--accent-gradient': `linear-gradient(135deg, ${primary} 0%, ${secondary} 100%)`,
    '--accent-glow': rgbaString(primary, glowAlpha),
    '--accent-glow-strong': rgbaString(primary, glowStrongAlpha),
    '--text-gradient': `linear-gradient(135deg, ${primary} 0%, ${secondary} 100%)`,
    '--table-row-hover': rgbaString(primary, 0.07),
    '--sidebar-user-bg': rgbaString(primary, 0.05),
    '--radial-glow-1': rgbaString(primary, 0.06),
    '--radial-glow-2': rgbaString(secondary, 0.04),
    '--card-shadow': isLight ? 'rgba(0, 0, 0, 0.08)' : 'rgba(0, 0, 0, 0.45)',
  }
}

// Master function to apply any theme to the DOM
export function applyTheme(themeId, customThemeConfig) {
  if (typeof document === 'undefined') return

  const root = document.documentElement
  let varsToApply = {}

  if (themeId === 'custom') {
    varsToApply = generateCustomThemeVars(customThemeConfig)
    root.setAttribute('data-theme', 'custom')
  } else {
    const preset = THEME_PRESETS.find(p => p.id === themeId) || THEME_PRESETS[0]
    varsToApply = preset.vars
    root.setAttribute('data-theme', preset.id)
  }

  // Check if current theme is light mode
  const isLight = varsToApply['--text-primary'] === '#0f172a'
  root.setAttribute('data-theme-mode', isLight ? 'light' : 'dark')

  // Apply all CSS variables to root element
  Object.entries(varsToApply).forEach(([property, value]) => {
    root.style.setProperty(property, value)
  })
}
